QStringList CsvExporter::lossReport(const Database& db)
{
    QStringList report;
    // Always true: nothing of the database's own settings is in the file
    report << QObject::tr("The settings of the database itself (its name and description, history limits, recycle bin "
                          "and the like) are not saved.");

    QStringList emptyFolders;
    QStringList foldersWithSettings;
    QStringList oddFolderNames;
    QStringList joinedFolders;
    for (const Group* group : db.rootGroup()->groupsRecursive(true)) {
        const auto path = folderPath(group);
        const auto* parent = group->parentGroup();
        // only the top folder of a branch without entries is named
        if (parent && group->entriesRecursive().isEmpty() && !parent->entriesRecursive().isEmpty()) {
            emptyFolders << path;
        }
        if (folderHasOwnSettings(group)) {
            foldersWithSettings << path;
        }
        if (group->name().isEmpty() || group->name().contains('/')) {
            oddFolderNames << path;
        }
        QSet<QString> seen;
        QSet<QString> reported;
        for (const Group* child : group->children()) {
            if (!seen.contains(child->name())) {
                seen.insert(child->name());
            } else if (!reported.contains(child->name())) {
                reported.insert(child->name());
                joinedFolders << folderPath(child);
            }
        }
    }

    QStringList entriesWithPicture;
    for (const Entry* entry : db.rootGroup()->entriesRecursive()) {
        if (usesPictureAsIcon(entry)) {
            entriesWithPicture << entry->title();
        }
    }

    if (!emptyFolders.isEmpty()) {
        report << QObject::tr("%n empty folder(s) are not saved, because a CSV file only holds entries: %1.",
                              "",
                              emptyFolders.size())
                      .arg(namesText(emptyFolders));
    }
    if (!foldersWithSettings.isEmpty()) {
        report << QObject::tr("A folder keeps only its name. The notes, icon, tags, expiry and other settings of %n "
                              "folder(s) are not saved: %1.",
                              "",
                              foldersWithSettings.size())
                      .arg(namesText(foldersWithSettings));
    }
    if (!entriesWithPicture.isEmpty()) {
        report << QObject::tr("%n entry(ies) (or older versions of them) use a picture of their own as icon; only the "
                              "number of a standard icon is saved: %1.",
                              "",
                              entriesWithPicture.size())
                      .arg(namesText(entriesWithPicture));
    }
    if (!joinedFolders.isEmpty()) {
        report << QObject::tr("Folders with the same name in the same place are joined into one when the file is "
                              "imported: %1.")
                      .arg(namesText(joinedFolders));
    }
    if (!oddFolderNames.isEmpty()) {
        report << QObject::tr("A folder name that is empty or contains a \"/\" is split into other folders when the "
                              "file is imported: %1.")
                      .arg(namesText(oddFolderNames));
    }
    return report;
}

bool CsvExporter::exportDatabase(const QString& filename, const QSharedPointer<const Database>& db)
{
    // write to a temporary file and replace the target only once everything was written, so a crash,
    // a full disk or an interruption never leaves a truncated export in place of the previous file.
    QSaveFile file(filename);
    file.setDirectWriteFallback(true);
    if (!file.open(QIODevice::WriteOnly)) {
        m_error = file.errorString();
        return false;
    }

    if (!exportDatabase(&file, db)) {
        file.cancelWriting();
        return false;
    }

    if (!file.commit()) {
        m_error = file.errorString();
        return false;
    }
    return true;
}

bool CsvExporter::exportDatabase(QIODevice* device, const QSharedPointer<const Database>& db)
{
    if (!writeText(device, exportHeader())) {
        return false;
    }

    // stream entry by entry; attachments are exported too and can be large
    return writeGroup(device, db->rootGroup(), QString());
}

QString CsvExporter::exportDatabase(const QSharedPointer<const Database>& db)
{
    return exportHeader() + exportGroup(db->rootGroup());
}

QString CsvExporter::errorString() const
{
    return m_error;
}

bool CsvExporter::writeText(QIODevice* device, const QString& text)
{
    const auto data = text.toUtf8();
    // a short write is a failure too, not only -1
    if (device->write(data) != data.size()) {
        m_error = device->errorString();
        if (m_error.isEmpty()) {
            m_error = QObject::tr("Not all data could be written.");
        }
        return false;
    }
    return true;
}

QString CsvExporter::exportHeader()
{
    QString header;
    addColumn(header, "Group");
    addColumn(header, "Title");
    addColumn(header, "Username");
    addColumn(header, "Password");
    addColumn(header, "URL");
    addColumn(header, "Notes");
    addColumn(header, "TOTP");
    addColumn(header, "Icon");
    addColumn(header, "Last Modified");
    addColumn(header, "Created");
    // everything below was not exported before
    addColumn(header, "Tags");
    addColumn(header, "Expires");
    addColumn(header, "Expiry Time");
    addColumn(header, "Last Accessed");
    addColumn(header, "Location Changed");
    addColumn(header, "Usage Count");
    addColumn(header, "UUID");
    addColumn(header, "Custom Attributes");
    addColumn(header, "Auto-Type");
    addColumn(header, "Attachments");
    addColumn(header, "History");
    // appended later still, so the columns before keep their positions
    addColumn(header, "Protected Attributes");
    addColumn(header, "Override URL");
    addColumn(header, "Foreground Color");
    addColumn(header, "Background Color");
    addColumn(header, "Exclude From Reports");
    addColumn(header, "Custom Data");
    addColumn(header, "Exact Text");
    return header + QString("\n");
}

QString CsvExporter::exportEntry(const Entry* entry, const QString& groupPath)
{
    QString line;

    // text that holds half an emoji is written in the plain cell with a replacement character, and exactly in
    // the last column (heading of the cell -> text). Every entry without such text leaves that column empty.
    QJsonObject exactText;
    auto addText = [this, &line, &exactText](const char* heading, const QString& text) {
        if (hasLoneSurrogate(text)) {
            exactText.insert(QLatin1String(heading), text);
        }
        addColumn(line, plainCellText(text));
    };

    addText("Group", groupPath);
    addText("Title", entry->title());
    addText("Username", entry->username());
    addText("Password", entry->password());
    addText("URL", entry->url());
    addText("Notes", entry->notes());
    addText("TOTP", entry->totpSettingsString());
    addColumn(line, QString::number(entry->iconNumber()));
    addColumn(line, isoTime(entry->timeInfo().lastModificationTime()));
    addColumn(line, isoTime(entry->timeInfo().creationTime()));
    addText("Tags", entry->tags());
    addColumn(line, entry->timeInfo().expires() ? "true" : "false");
    addColumn(line, isoTime(entry->timeInfo().expiryTime()));
    addColumn(line, isoTime(entry->timeInfo().lastAccessTime()));
    addColumn(line, isoTime(entry->timeInfo().locationChanged()));
    addColumn(line, QString::number(entry->timeInfo().usageCount()));
    addColumn(line, entry->uuidToHex());
    addColumn(line, toJson(customAttributes(entry)));
    addColumn(line, toJson(autoTypeSettings(entry)));
    addColumn(line, toJson(attachments(entry)));
    addColumn(line, toJson(history(entry)));
    addColumn(line, toJson(protectedAttributes(entry)));
    addText("Override URL", entry->overrideUrl());
    addText("Foreground Color", entry->foregroundColor());
    addText("Background Color", entry->backgroundColor());
    addColumn(line, entry->excludeFromReports() ? "true" : "false");
    addColumn(line, toJson(customData(entry)));
    addColumn(line, toJson(exactText));

    line.append("\n");
    return line;
}

QString CsvExporter::exportGroup(const Group* group, QString groupPath)
{
    QString response;
    if (!groupPath.isEmpty()) {
        groupPath.append("/");
    }
    groupPath.append(group->name());

    const QList<Entry*>& entryList = group->entries();
    for (const Entry* entry : entryList) {
        response.append(exportEntry(entry, groupPath));
    }

    const QList<Group*>& children = group->children();
    for (const Group* child : children) {
        response.append(exportGroup(child, groupPath));
    }

    return response;
}

bool CsvExporter::writeGroup(QIODevice* device, const Group* group, QString groupPath)
{
    if (!groupPath.isEmpty()) {
        groupPath.append("/");
    }
    groupPath.append(group->name());

    const QList<Entry*>& entryList = group->entries();
    for (const Entry* entry : entryList) {
        if (!writeText(device, exportEntry(entry, groupPath))) {
            return false;
        }
    }

    const QList<Group*>& children = group->children();
    for (const Group* child : children) {
        if (!writeGroup(device, child, groupPath)) {
            return false;
        }
    }

    return true;
}

void CsvExporter::addColumn(QString& str, const QString& column)
{
    if (!str.isEmpty()) {
        str.append(",");
    }

    str.append("\"");
    str.append(QString(column).replace("\"", "\"\""));
    str.append("\"");
}
