    // columns after "Created" were appended so that the original ten keep their positions.
    // Structured values are JSON (compact) inside one CSV cell; an entry without such data leaves the cell empty.

    // Qt's JSON reader drops a U+FEFF that starts a string value (the one character of all the unusual ones that it
    // loses). Written as the JSON escape it comes back.
    QString jsonText(const QByteArray& json)
    {
        return QString::fromUtf8(json).replace(QChar(0xFEFF), QLatin1String("\\ufeff"));
    }

    QString toJson(const QJsonObject& object)
    {
        return object.isEmpty() ? QString() : jsonText(QJsonDocument(object).toJson(QJsonDocument::Compact));
    }

    QString toJson(const QJsonArray& array)
    {
        return array.isEmpty() ? QString() : jsonText(QJsonDocument(array).toJson(QJsonDocument::Compact));
    }

    QString isoTime(const QDateTime& time)
    {
        return time.toString(Qt::ISODate);
    }

    // Half of an emoji: a UTF-16 surrogate without its partner. A CSV file is UTF-8 text, which cannot carry it, but
    // JSON text can (as an escape), so the exact text goes into the "Exact Text" column.
    bool isLoneSurrogate(const QString& text, int i)
    {
        const auto unit = text.at(i).unicode();
        if (QChar::isHighSurrogate(unit)) {
            return i + 1 >= text.size() || !QChar::isLowSurrogate(text.at(i + 1).unicode());
        }
        if (QChar::isLowSurrogate(unit)) {
            return i == 0 || !QChar::isHighSurrogate(text.at(i - 1).unicode());
        }
        return false;
    }

    bool hasLoneSurrogate(const QString& text)
    {
        for (int i = 0; i < text.size(); ++i) {
            if (isLoneSurrogate(text, i)) {
                return true;
            }
        }
        return false;
    }

    // The text as a plain cell can hold it: half an emoji becomes the replacement character
    QString plainCellText(const QString& text)
    {
        QString result = text;
        for (int i = 0; i < result.size(); ++i) {
            if (isLoneSurrogate(result, i)) {
                result[i] = QChar::ReplacementCharacter;
            }
        }
        return result;
    }

    // Every custom field: the ones that are not a standard field (title, user name, password, URL, notes). That
    // includes the fields passkeys are stored in, which Advanced does not list but which are part of the entry.
    QStringList customKeys(const Entry* entry)
    {
        QStringList keys;
        for (const auto& key : entry->attributes()->keys()) {
            if (!EntryAttributes::isDefaultAttribute(key)) {
                keys << key;
            }
        }
        return keys;
    }

    QJsonObject customAttributes(const Entry* entry)
    {
        QJsonObject attributes;
        for (const auto& key : customKeys(entry)) {
            attributes.insert(key, entry->attributes()->value(key));
        }
        return attributes;
    }

    // The names of the custom fields that are hidden (protected) in the entry editor
    QJsonArray protectedAttributes(const Entry* entry)
    {
        QJsonArray names;
        for (const auto& key : customKeys(entry)) {
            if (entry->attributes()->isProtected(key)) {
                names.append(key);
            }
        }
        return names;
    }

    // What the browser integration and other programs store with an entry (not the automatic time stamp)
    QJsonObject customData(const Entry* entry)
    {
        QJsonObject data;
        const auto* entryData = entry->customData();
        for (const auto& key : entryData->keys()) {
            if (!entryData->isAutoGenerated(key)) {
                data.insert(key, entryData->value(key));
            }
        }
        return data;
    }

    QJsonObject autoTypeSettings(const Entry* entry)
    {
        QJsonArray associations;
        for (const auto& association : entry->autoTypeAssociations()->getAll()) {
            associations.append(QJsonObject{{"window", association.window}, {"sequence", association.sequence}});
        }

        // Only exported when it differs from the defaults (enabled, no obfuscation, default sequence, no windows)
        if (entry->autoTypeEnabled() && entry->autoTypeObfuscation() == 0 && entry->defaultAutoTypeSequence().isEmpty()
            && associations.isEmpty()) {
            return {};
        }

        QJsonObject settings;
        settings.insert("enabled", entry->autoTypeEnabled());
        settings.insert("obfuscation", entry->autoTypeObfuscation());
        settings.insert("defaultSequence", entry->defaultAutoTypeSequence());
        settings.insert("associations", associations);
        return settings;
    }

    QJsonObject attachments(const Entry* entry)
    {
        QJsonObject result;
        const auto* entryAttachments = entry->attachments();
        for (const auto& key : entryAttachments->keys()) {
            result.insert(key, QString::fromLatin1(entryAttachments->value(key).toBase64()));
        }
        return result;
    }

    QJsonArray history(const Entry* entry)
    {
        QJsonArray snapshots;
        for (const auto* item : entry->historyItems()) {
            QJsonObject snapshot;
            snapshot.insert("title", item->title());
            snapshot.insert("username", item->username());
            snapshot.insert("password", item->password());
            snapshot.insert("url", item->url());
            snapshot.insert("notes", item->notes());
            snapshot.insert("modified", isoTime(item->timeInfo().lastModificationTime()));
            const auto attributes = customAttributes(item);
            if (!attributes.isEmpty()) {
                snapshot.insert("attributes", attributes);
            }
            const auto hidden = protectedAttributes(item);
            if (!hidden.isEmpty()) {
                snapshot.insert("protectedAttributes", hidden);
            }

            // an older version holds everything the entry had at the time, so the rest of it is written
            // too. What a new entry has anyway is left out, so an older version that never differed stays small, and
            // a file written before these keys existed imports with those defaults.
            const auto& times = item->timeInfo();
            snapshot.insert("created", isoTime(times.creationTime()));
            snapshot.insert("accessed", isoTime(times.lastAccessTime()));
            snapshot.insert("locationChanged", isoTime(times.locationChanged()));
            snapshot.insert("expiryTime", isoTime(times.expiryTime()));
            if (times.expires()) {
                snapshot.insert("expires", true);
            }
            if (times.usageCount() != 0) {
                snapshot.insert("usageCount", times.usageCount());
            }
            if (item->iconNumber() != Entry::DefaultIconNumber) {
                snapshot.insert("icon", item->iconNumber());
            }
            if (!item->tags().isEmpty()) {
                snapshot.insert("tags", item->tags());
            }
            if (!item->foregroundColor().isEmpty()) {
                snapshot.insert("foregroundColor", item->foregroundColor());
            }
            if (!item->backgroundColor().isEmpty()) {
                snapshot.insert("backgroundColor", item->backgroundColor());
            }
            if (!item->overrideUrl().isEmpty()) {
                snapshot.insert("overrideUrl", item->overrideUrl());
            }
            if (item->excludeFromReports()) {
                snapshot.insert("excludeFromReports", true);
            }
            const auto itemAutoType = autoTypeSettings(item);
            if (!itemAutoType.isEmpty()) {
                snapshot.insert("autoType", itemAutoType);
            }
            const auto itemCustomData = customData(item);
            if (!itemCustomData.isEmpty()) {
                snapshot.insert("customData", itemCustomData);
            }
            // Attachments: one that is the same as the entry's own attachment of that name is written as null (the
            // import takes it from the entry), so a large attachment is not repeated for every older version
            QJsonObject olderAttachments;
            for (const auto& name : item->attachments()->keys()) {
                const auto data = item->attachments()->value(name);
                if (entry->attachments()->hasKey(name) && entry->attachments()->value(name) == data) {
                    olderAttachments.insert(name, QJsonValue::Null);
                } else {
                    olderAttachments.insert(name, QString::fromLatin1(data.toBase64()));
                }
            }
            if (!olderAttachments.isEmpty()) {
                snapshot.insert("attachments", olderAttachments);
            }
            snapshots.append(snapshot);
        }
        return snapshots;
    }

    // --- what a CSV file cannot hold (CsvExporter::lossReport) ---

    QString quoted(const QString& text)
    {
        return QStringLiteral("\"") + text + QStringLiteral("\"");
    }

    // "a", "b", "c", "d", "e" and 4 more
    QString namesText(const QStringList& names)
    {
        constexpr int shown = 5;
        QStringList part;
        for (int i = 0; i < qMin<int>(shown, names.size()); ++i) {
            part << quoted(names.at(i));
        }
        auto text = part.join(", ");
        if (names.size() > shown) {
            text += QObject::tr(" and %n more", "", names.size() - shown);
        }
        return text;
    }

    // The folder as the CSV file writes it: names joined by "/", starting with the root folder
    QString folderPath(const Group* group)
    {
        QStringList names;
        for (const Group* g = group; g; g = g->parentGroup()) {
            names.prepend(g->name());
        }
        return names.join("/");
    }

    bool hasOwnData(const CustomData* data)
    {
        for (const auto& key : data->keys()) {
            if (!data->isAutoGenerated(key)) {
                return true;
            }
        }
        return false;
    }

    // A folder keeps only its name in a CSV file; true when it has something else a person set
    bool folderHasOwnSettings(const Group* group)
    {
        // mergeMode() answers with the mode in effect; the folder has a mode of its own when that is not the one it
        // would inherit (the root folder falls back to KeepNewer)
        const auto inheritedMergeMode = group->parentGroup() ? group->parentGroup()->mergeMode() : Group::KeepNewer;
        return !group->notes().isEmpty() || !group->tags().isEmpty()
               || (group->iconNumber() != Group::DefaultIconNumber
                   && group->iconNumber() != Group::OpenFolderIconNumber)
               || !group->iconUuid().isNull() || group->timeInfo().expires()
               || group->autoTypeEnabled() != Group::Inherit || group->searchingEnabled() != Group::Inherit
               || !group->defaultAutoTypeSequence().isEmpty() || group->mergeMode() != inheritedMergeMode
               || hasOwnData(group->customData());
    }

    // The only thing of an entry that a CSV file cannot carry is a picture it uses as its icon (the file has the number
    // of a standard icon); older versions of the entry can use one as well
    bool usesPictureAsIcon(const Entry* entry)
    {
        if (!entry->iconUuid().isNull()) {
            return true;
        }
        for (const Entry* item : entry->historyItems()) {
            if (!item->iconUuid().isNull()) {
                return true;
            }
        }
        return false;
    }
